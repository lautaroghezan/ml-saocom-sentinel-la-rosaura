features = []

for lote_id, coords_latlon in lotes_latlon.items():

    # Invertimos (lat, lon) -> (lon, lat)
    coords_lonlat = [
        [lon, lat]
        for lat, lon in coords_latlon
    ]

    feature = {
        "type": "Feature",
        "properties": {
            "lote_id": lote_id,
            "fuente": "delimitacion La Rosaura suministrada por el usuario"
        },
        "geometry": {
            "type": "Polygon",
            "coordinates": [coords_lonlat]
        }
    }

    features.append(feature)


geojson = {
    "type": "FeatureCollection",
    "name": "potreros_la_rosaura",
    "crs": {
        "type": "name",
        "properties": {
            "name": "urn:ogc:def:crs:OGC:1.3:CRS84"
        }
    },
    "features": features
}


with open(SALIDA, "w", encoding="utf-8") as f:
    json.dump(
        geojson,
        f,
        ensure_ascii=False,
        indent=2
    )


